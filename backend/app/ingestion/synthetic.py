"""Deterministic SYNTHETIC development data. Never Elexon observations.

Shaped like the real API rows (hourly WINDFOR vintages at 8 publish times a day, half-hourly FUELHH) so
that the whole pipeline can run offline. Every artefact built from it carries ``is_synthetic = True``.
"""

from __future__ import annotations

import math
from datetime import UTC, date, datetime, timedelta
from typing import Any

import numpy as np

from app.ingestion.snapshot import (
    RawSnapshot,
    build_manifest,
    encode_files,
    raw_from_rows,
)

SYNTHETIC_NOTICE = (
    "SYNTHETIC DEVELOPMENT FIXTURE - generated by app.ingestion.synthetic. "
    "These values are invented and are NOT Elexon observations."
)
PUBLISH_SLOTS_UTC = ("02:30", "04:30", "07:30", "09:30", "11:30", "15:30", "18:30", "22:30")


def _z(dt: datetime) -> str:
    return dt.astimezone(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


def _truth(t: datetime) -> float:
    h = (t - datetime(2026, 1, 1, tzinfo=UTC)).total_seconds() / 3600.0
    return (
        9000.0
        + 4000.0 * math.sin(2 * math.pi * h / 40.0)
        + 1500.0 * math.sin(2 * math.pi * h / 9.0)
    )


def build_synthetic_rows(
    start: date = date(2026, 1, 1),
    end: date = date(2026, 1, 31),
    seed: int = 20260101,
) -> tuple[list[dict[str, Any]], list[dict[str, Any]], datetime, datetime]:
    """Return (fuelhh_rows, windfor_rows, publish_from, publish_to). Deterministic for a seed."""
    rng = np.random.default_rng(seed)
    t0 = datetime(start.year, start.month, start.day, tzinfo=UTC)
    t1 = datetime(end.year, end.month, end.day, tzinfo=UTC) + timedelta(days=1)

    fuelhh: list[dict[str, Any]] = []
    t = t0
    while t < t1:
        sp = int((t - t.replace(hour=0, minute=0)).total_seconds() // 1800) + 1
        fuelhh.append(
            {
                "dataset": "FUELHH",
                "publishTime": _z(t + timedelta(minutes=30)),
                "startTime": _z(t),
                "settlementDate": t.date().isoformat(),
                "settlementPeriod": sp,
                "fuelType": "WIND",
                "generation": round(_truth(t) + rng.normal(0, 150)),
            }
        )
        t += timedelta(minutes=30)

    publish_from = t0 - timedelta(days=5)
    publish_to = t1 + timedelta(days=3)
    windfor: list[dict[str, Any]] = []
    day = publish_from.replace(hour=0, minute=0)
    while day < publish_to:
        for slot in PUBLISH_SLOTS_UTC:
            hh, mm = (int(x) for x in slot.split(":"))
            pub = day.replace(hour=hh, minute=mm)
            first = pub.replace(minute=0) - timedelta(hours=25)
            for k in range(73):
                st = first + timedelta(hours=k)
                lead_h = max((st - pub).total_seconds() / 3600.0, 0.0)
                sigma = 400.0 + 25.0 * lead_h
                val = _truth(st + timedelta(minutes=15)) * 1.1 + rng.normal(0, sigma)
                windfor.append(
                    {
                        "dataset": "WINDFOR",
                        "publishTime": _z(pub),
                        "startTime": _z(st),
                        "generation": round(max(val, 0.0)),
                    }
                )
        day += timedelta(days=1)
    return fuelhh, windfor, publish_from, publish_to


def build_synthetic_snapshot(seed: int = 20260101) -> RawSnapshot:
    fuelhh, windfor, publish_from, publish_to = build_synthetic_rows(seed=seed)
    fh_bytes, wf_bytes = encode_files(fuelhh, windfor)
    manifest = build_manifest(
        fuelhh_bytes=fh_bytes,
        windfor_bytes=wf_bytes,
        fuelhh_row_count=len(fuelhh),
        windfor_row_count=len(windfor),
        sources=[{"dataset": "SYNTHETIC", "endpoint": "app.ingestion.synthetic", "seed": seed}],
        retrieved_at=datetime(2026, 1, 1, tzinfo=UTC),
        delivery_start=date(2026, 1, 1),
        delivery_end=date(2026, 1, 31),
        publish_from=publish_from,
        publish_to=publish_to,
        is_synthetic=True,
        tool_version="synthetic",
        notice=SYNTHETIC_NOTICE,
    )
    return raw_from_rows(fuelhh, windfor, manifest)
